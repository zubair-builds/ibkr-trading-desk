"""Morning prefilter: screen the S&P 500 for gap-ups and write watchlist.txt."""
import argparse
import json
import sys
import time
from datetime import datetime
from pathlib import Path
from zoneinfo import ZoneInfo

import yfinance as yf
from dotenv import load_dotenv

ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT))
from src.sp500_tickers import SP500_TICKERS  # noqa: E402
from src.spus_tickers import SPUS_TICKERS  # noqa: E402
from src.notify import notify  # noqa: E402

UNIVERSES = {"spus": SPUS_TICKERS, "sp500": SP500_TICKERS}
DEFAULT_UNIVERSE = "spus"

WATCHLIST_PATH = Path("watchlist.txt")
DEFAULT_MIN_GAP_PCT = 3.0
DEFAULT_MIN_PRICE = 3.0
MAX_SURVIVORS = 20
ET = ZoneInfo("America/New_York")


def to_yahoo(t: str) -> str:
    return t.replace(" ", "-")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--min-gap", type=float, default=DEFAULT_MIN_GAP_PCT)
    ap.add_argument("--min-price", type=float, default=DEFAULT_MIN_PRICE)
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--universe", choices=sorted(UNIVERSES), default=DEFAULT_UNIVERSE)
    a = ap.parse_args()

    load_dotenv(ROOT / ".env")
    start = time.time()
    ibkr_tickers = list(UNIVERSES[a.universe])
    yahoo_map = {to_yahoo(t): t for t in ibkr_tickers}
    total = len(ibkr_tickers)
    out_path = ROOT / WATCHLIST_PATH

    df = yf.download(
        tickers=" ".join(yahoo_map.keys()),
        period="2d",
        interval="1d",
        group_by="ticker",
        threads=5,
        progress=False,
        auto_adjust=True,
    )
    if df is None or df.empty:
        notify("Prefilter FAILED", "yf.download returned empty dataframe", "urgent", "warning")
        print(json.dumps({"success": False, "error": "yf.download returned empty dataframe",
                          "total_screened": total}))
        sys.exit(1)

    survivors, below_gap, below_price, failed = [], [], [], []
    for ysym, isym in yahoo_map.items():
        try:
            bars = df[ysym].dropna(how="all")
            yesterday_close = float(bars.iloc[-2]["Close"])
            today_open = float(bars.iloc[-1]["Open"])
            today_close = float(bars.iloc[-1]["Close"])
            today_high = float(bars.iloc[-1]["High"])
            today_low = float(bars.iloc[-1]["Low"])
            if not yesterday_close or yesterday_close != yesterday_close or today_close != today_close:
                raise ValueError("missing price")
            gap_pct = (today_close - yesterday_close) / yesterday_close * 100
            if today_close < a.min_price:
                below_price.append(isym)
            elif gap_pct < a.min_gap:
                below_gap.append(isym)
            else:
                survivors.append({"ticker": isym, "gap_pct": gap_pct, "open": today_open,
                                  "prev": yesterday_close, "close": today_close,
                                  "high": today_high, "low": today_low})
        except (KeyError, IndexError, ValueError):
            failed.append(isym)

    survivors.sort(key=lambda s: s["gap_pct"], reverse=True)
    survivors = survivors[:MAX_SURVIVORS]

    if not a.dry_run:
        now = datetime.now(ET).strftime("%Y-%m-%d %H:%M %Z")
        lines = [
            f"# Auto-generated by morning_prefilter.py at {now}",
            f"# Universe: {a.universe}",
            f"# Filters: gap >= {a.min_gap:g}%, price >= ${a.min_price:g}",
            "# Source: yfinance (screening only); IBKR handles execution",
            f"# Survivors: {len(survivors)} (capped at {MAX_SURVIVORS}) of {total}",
            "#",
            "# ticker  # gap +X.XX%  open $X.XX  prev $X.XX",
        ]
        for s in survivors:
            lines.append(f"{s['ticker']}  # gap {s['gap_pct']:+.2f}%  open ${s['open']:.2f}  prev ${s['prev']:.2f}")
        try:
            _aw = json.loads((Path(__file__).parent / "rules.json").read_text()).get("always_watch", [])
        except Exception:
            _aw = []
        _have = {s["ticker"] for s in survivors}
        for t in _aw:
            if t not in _have:
                lines.append(f"{t}  # always_watch")
        out_path.write_text("\n".join(lines) + "\n", encoding="utf-8")

    ratio = len(failed) / total if total else 0
    if ratio >= 0.95:
        print("ALERT: Yahoo-wide failure suspected; check yfinance changelog", file=sys.stderr)
        notify("Prefilter ALERT", "Yahoo-wide failure suspected; check yfinance changelog", "urgent", "warning")
    elif ratio >= 0.30:
        print(f"ALERT: yfinance degradation (failed {len(failed)}/{total})", file=sys.stderr)
        notify("Prefilter ALERT", f"yfinance degradation (failed {len(failed)}/{total})", "high", "warning")

    if not a.dry_run:
        top = ", ".join(f"{s['ticker']} {s['gap_pct']:+.1f}%" for s in survivors[:10]) or "none"
        _body = f"{len(survivors)}/{total} survivors in {time.time() - start:.0f}s\n" + "\n".join(
            f"- {s['ticker']} {s['gap_pct']:+.1f}%" for s in survivors[:20])
        notify(f"Prefilter {datetime.now(ET).strftime('%H:%M')} ET", _body, "default", "clipboard")
    print(json.dumps({
        "success": True,
        "universe": a.universe,
        "total_screened": total,
        "survivors_count": len(survivors),
        "below_gap": len(below_gap),
        "below_price": len(below_price),
        "failed": len(failed),
        "elapsed_seconds": round(time.time() - start, 2),
        "top_20_survivors": [f"{s['ticker']} ({s['gap_pct']:+.2f}%)" for s in survivors],
        "watchlist_path": None if a.dry_run else str(out_path),
    }, indent=2))


if __name__ == "__main__":
    main()
